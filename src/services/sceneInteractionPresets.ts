export function getInteractionPresetById(
  id: SceneInteractionPresetId | null | undefined
): SceneInteractionPreset | null {
  if (!id) return null;
  return SCENE_INTERACTION_PRESETS.find((p) => p.id === id) || null;
}

export function getSupportSurfaceById(
  id: SupportSurfaceId | null | undefined
): BedroomSupportSurfaceSpec | null {
  if (!id) return null;
  return BEDROOM_SUPPORT_SURFACES.find((s) => s.id === id) || null;
}

/**
 * Infers the active support surface from the character's current pose and position.
 */
export function inferActiveSupportSurface(pose: CharacterPose3DSettings): BedroomSupportSurfaceSpec {
  const preset = getInteractionPresetById(pose.interactionPresetId);
  const posX = pose.characterPosX ?? 0;
  const posZ = pose.characterPosZ ?? 0;
  const seatY = pose.seatHeightY ?? null;

  if (preset) {
    if (preset.id === 'bed_bench_sit_forward' || preset.id === 'stand_both_hands_on_bench') {
      return getSupportSurfaceById('bed_bench')!;
    }
    if (preset.id === 'window_bench_sit_upright' || preset.id === 'window_bench_recline_side') {
      return getSupportSurfaceById('window_bench')!;
    }
    if (preset.id === 'bed_sit_headboard_pillows' || preset.id === 'bed_lie_recline_pillows') {
      return getSupportSurfaceById('bed_pillows')!;
    }
    if (
      preset.id === 'stand_beside_nightstand' ||
      preset.id === 'nightstand_reach_hand' ||
      preset.id === 'nightstand_crouch_beside'
    ) {
      return getSupportSurfaceById('bedside_table')!;
    }
    if (preset.furnitureTarget === 'bed') {
      return preset.category === 'bed_sitting' && posZ > -1.35
        ? getSupportSurfaceById('bed_edge_front')!
        : getSupportSurfaceById('bed_mattress')!;
    }
    if (preset.furnitureTarget === 'chair') {
      return posX < -2.3
        ? getSupportSurfaceById('window_bench')!
        : getSupportSurfaceById('club_armchair')!;
    }
    if (preset.furnitureTarget === 'desk') {
      return getSupportSurfaceById('desk_console')!;
    }
    if (preset.furnitureTarget === 'wall') {
      return getSupportSurfaceById('studio_wall')!;
    }
  }

  if (seatY !== null) {
    if (posX >= 0.35 && posX <= 2.15 && posZ >= -2.85 && posZ <= -0.82) {
      return posZ <= -2.1
        ? getSupportSurfaceById('bed_pillows')!
        : posZ >= -1.25
        ? getSupportSurfaceById('bed_edge_front')!
        : getSupportSurfaceById('bed_mattress')!;
    }
    if (posX >= 0.5 && posX <= 2.0 && posZ > -0.82 && posZ <= -0.15) {
      return getSupportSurfaceById('bed_bench')!;
    }
    if (posX <= -2.3 && posZ >= -2.55 && posZ <= -1.15) {
      return getSupportSurfaceById('window_bench')!;
    }
    if (posX <= -1.15 && posZ >= -0.2 && posZ <= 0.65) {
      return getSupportSurfaceById('club_armchair')!;
    }
  }

  if (Math.abs(posX) <= 1.8 && Math.abs(posZ) <= 1.6) {
    return getSupportSurfaceById('area_rug')!;
  }
  return getSupportSurfaceById('floor_center')!;
}

/**
 * Safely clamps horizontal X/Z placement so that:
 * - Elevated poses (seated or lying on bed, chair, window bench, foot bench, desk) stay safely on
 *   their supporting furniture surface without falling off or snapping to standing.
 * - Floor/standing poses stay within room boundaries.
 */
export function clampPosePlacementToSupportBounds(
  pose: CharacterPose3DSettings,
  targetX: number,
  targetZ: number,
  environment: PlayboardEnvironment = 'studio_bedroom'
): { x: number; z: number; seatHeightY: number | null; clampedToSupport: boolean } {
  const seatY = pose.seatHeightY ?? null;

  if (environment === 'studio_bedroom' && seatY !== null) {
    const support = inferActiveSupportSurface(pose);
    if (support.seatHeightY !== null) {
      const clampedX = Math.max(support.bounds.minX, Math.min(support.bounds.maxX, targetX));
      const clampedZ = Math.max(support.bounds.minZ, Math.min(support.bounds.maxZ, targetZ));
      return {
        x: Number(clampedX.toFixed(3)),
        z: Number(clampedZ.toFixed(3)),
        seatHeightY: seatY,
        clampedToSupport: true,
      };
    }
  }

  const roomMinX = environment === 'studio_bedroom' ? -2.62 : -2.85;
  const roomMaxX = environment === 'studio_bedroom' ? 2.68 : 2.85;
  const roomMinZ = environment === 'studio_bedroom' ? -2.68 : -2.85;
  const roomMaxZ = environment === 'studio_bedroom' ? 2.75 : 2.85;

  return {
    x: Number(Math.max(roomMinX, Math.min(roomMaxX, targetX)).toFixed(3)),
    z: Number(Math.max(roomMinZ, Math.min(roomMaxZ, targetZ)).toFixed(3)),
    seatHeightY: seatY,
    clampedToSupport: false,
  };
}

export interface EvaluatedSceneInteraction {
  hasActiveInteraction: boolean;
  preset: SceneInteractionPreset | null;
  isStillAtAnchor: boolean;
  surfaceDescription: string;
  i2iActionDescription: string;
}

function isHandInContactWithDesk(hand: { x: number; y: number; z: number }): boolean {
  // Desk tabletop top surface is at Y=0.763m, X in [-2.74, -1.96], Z in [-0.575, 1.075]
  return (
    hand.x >= -2.85 &&
    hand.x <= -1.84 &&
    hand.z >= -0.65 &&
    hand.z <= 1.15 &&
    hand.y >= 0.64 &&
    hand.y <= 0.94
  );
}

function isHandInContactWithBed(hand: { x: number; y: number; z: number }): boolean {
  // Bed mattress/duvet top surface is around Y=0.45..0.54m, X in [0.41, 2.09], Z in [-2.90, -0.77]
  return (
    hand.x >= 0.34 &&
    hand.x <= 2.16 &&
    hand.z >= -2.95 &&
    hand.z <= -0.72 &&
    hand.y >= 0.36 &&
    hand.y <= 0.68
  );
}

/**
 * Evaluates whether the character is currently engaged in a scene interaction preset and
 * verifies whether the character's 3D landmarks (pelvis, upper back, hands) are still in physical
 * contact with the target furniture/scene anchor.
 *
 * - If the active environment does not contain the target bedroom furniture (`minimal_neutral` or
 *   `cyber_grid`), returns `hasActiveInteraction: false` so prompts never reference invisible objects.
 * - If the user moved the character away from the furniture or adjusted the limbs away from the
 *   contact surface, updates or disables the contact description accordingly.
 */
export function evaluateActiveSceneInteraction(
  pose: CharacterPose3DSettings,
  environment: PlayboardEnvironment = 'studio_bedroom'
): EvaluatedSceneInteraction {
  const preset = getInteractionPresetById(pose.interactionPresetId);
  if (!preset) {
    return {
      hasActiveInteraction: false,
      preset: null,
      isStillAtAnchor: false,
      surfaceDescription: '',
      i2iActionDescription: '',
    };
  }

  // Do not claim contact with bedroom-specific furniture (bed, chair, desk, wall) if the current environment lacks it
  if (
    environment !== 'studio_bedroom' &&
    (preset.requiresBedroomFurniture || preset.furnitureTarget === 'wall')
  ) {
    return {
      hasActiveInteraction: false,
      preset,
      isStillAtAnchor: false,
      surfaceDescription: '',
      i2iActionDescription: '',
    };
  }

  const posX = pose.characterPosX ?? preset.anchorX;
  const posZ = pose.characterPosZ ?? preset.anchorZ;
  const distFromAnchor = Math.hypot(posX - preset.anchorX, posZ - preset.anchorZ);
  const isOnBedSurface =
    preset.furnitureTarget === 'bed' &&
    preset.seatHeightY !== null &&
    posX >= 0.5 &&
    posX <= 2.0 &&
    posZ >= -2.72 &&
    posZ <= -0.82;
  const isStillAtAnchor = (distFromAnchor <= 0.55 || isOnBedSurface) && !pose.isWalking;

  if (!isStillAtAnchor) {
    return {
      hasActiveInteraction: false,
      preset,
      isStillAtAnchor: false,
      surfaceDescription: '',
      i2iActionDescription: '',
    };
  }

  const landmarks = computeCharacterWorldLandmarks(pose);
  const leftDeskContact = isHandInContactWithDesk(landmarks.leftHand);
  const rightDeskContact = isHandInContactWithDesk(landmarks.rightHand);
  const leftBedContact = isHandInContactWithBed(landmarks.leftHand);
  const rightBedContact = isHandInContactWithBed(landmarks.rightHand);

  let surfaceDescription = preset.environmentalContext;
  let i2iActionDescription = preset.i2iEnvironmentalAction;

  // Verify specific physical contact claims against actual 3D limb landmarks
  if (preset.id === 'chair_sit_arm_on_desk') {
    if (!rightDeskContact && !leftDeskContact) {
      surfaceDescription = 'seated in the studio chair beside the creator desk';
      i2iActionDescription = 'Position the subject seated on the studio chair next to the desk';
    }
  } else if (preset.id === 'floor_kneel_hands_on_bed') {
    if (!leftBedContact && !rightBedContact) {
      surfaceDescription = 'kneeling on the floor directly beside the platform bed';
      i2iActionDescription = 'Position the subject kneeling on the floor next to the bed';
    } else if (leftBedContact !== rightBedContact) {
      const side = leftBedContact ? 'left hand' : 'right hand';
      surfaceDescription = `kneeling on the floor beside the bed with the ${side} resting on the mattress surface`;
      i2iActionDescription = `Position the subject kneeling on the floor next to the bed with their ${side} resting on the mattress`;
    }
  } else if (preset.id === 'bed_sit_lean_back_hands') {
    if (!leftBedContact && !rightBedContact) {
      surfaceDescription = 'seated on the bed leaning casually backward';
      i2iActionDescription = 'Position the subject seated on the bed leaning backward';
    }
  } else if (preset.id === 'lean_forward_hands_on_desk') {
    if (!leftDeskContact && !rightDeskContact) {
      surfaceDescription = 'standing in front of the studio desk and leaning forward toward the tabletop';
      i2iActionDescription = 'Position the subject standing at the table and leaning forward';
    } else if (leftDeskContact !== rightDeskContact) {
      const side = leftDeskContact ? 'left hand' : 'right hand';
      surfaceDescription = `standing at the studio desk and leaning forward with the ${side} braced on the tabletop surface`;
      i2iActionDescription = `Position the subject standing at the table leaning forward with their ${side} braced on the tabletop`;
    }
  } else if (preset.id === 'stand_beside_desk_hand_rest') {
    if (!rightDeskContact && !leftDeskContact) {
      surfaceDescription = 'standing poised beside the studio table';
      i2iActionDescription = 'Position the subject standing poised beside the studio table';
    }
  } else if (preset.id === 'lean_back_desk_edge') {
    if (!leftDeskContact && !rightDeskContact) {
      surfaceDescription = 'leaning backward against the front edge of the studio table';
      i2iActionDescription = 'Position the subject leaning backward against the front edge of the table';
    }
  } else if (preset.id === 'lean_against_wall' || preset.id === 'stand_wall_shoulder_lean' || preset.id === 'stand_wall_back_relaxed_knees') {
    const backNearWall = landmarks.upperBack.z <= -2.55 || landmarks.pelvis.z <= -2.55;
    if (!backNearWall) {
      return {
        hasActiveInteraction: false,
        preset,
        isStillAtAnchor: false,
        surfaceDescription: '',
        i2iActionDescription: '',
      };
    }
  }

  return {
    hasActiveInteraction: true,
    preset,
    isStillAtAnchor: true,
    surfaceDescription,
    i2iActionDescription,
  };
}


